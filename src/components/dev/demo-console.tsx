"use client";

import { useState } from "react";
import Link from "next/link";
import { toast } from "sonner";
import { LoaderCircleIcon, RotateCcwIcon } from "lucide-react";
import { config } from "@/lib/config";
import { Button } from "@/components/ui/button";
import { CopyButton } from "@/components/common/copy-button";

/**
 * QLT-12: a one-click reset for the seeded demo project. The reset endpoint
 * only exists in the contract mocks, so the button explains itself when the
 * app runs against a real backend.
 */
export function DemoConsole({
  slug,
  token,
  endpointUrl,
}: {
  slug: string;
  token: string;
  endpointUrl: string;
}) {
  const [resetting, setResetting] = useState(false);
  const [message, setMessage] = useState<string | null>(null);

  async function reset() {
    setResetting(true);
    setMessage(null);
    try {
      const response = await fetch(`${config.apiBaseUrl}/api/v1/__mock/reset`, {
        method: "POST",
        headers: { Accept: "application/json" },
        credentials: "omit",
        cache: "no-store",
      });
      if (!response.ok) {
        setMessage(
          "The reset endpoint is only available in mock mode. Against a real backend, create a new project instead.",
        );
        return;
      }
      setMessage("Demo data reset. The seeded project and its logs are back.");
      toast.success("Demo data reset");
    } catch {
      setMessage(
        "The API could not be reached, so nothing was reset. Check that the backend is running.",
      );
    } finally {
      setResetting(false);
    }
  }

  return (
    <div className="space-y-6">
      <section className="rounded-xl border border-white/10 bg-white/[0.02] p-5">
        <h2 className="text-sm font-semibold text-zinc-100">Seeded demo project</h2>
        <dl className="mt-3 space-y-3 text-sm">
          <div className="flex flex-wrap items-center gap-2">
            <dt className="w-20 shrink-0 text-xs text-zinc-500">Slug</dt>
            <dd className="min-w-0 flex-1">
              <code className="font-mono text-xs text-zinc-200">{slug}</code>
            </dd>
            <CopyButton
              value={slug}
              label="Copy demo slug"
              toastMessage="Demo slug copied."
              variant="ghost"
              size="xs"
            />
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <dt className="w-20 shrink-0 text-xs text-zinc-500">Token</dt>
            <dd className="min-w-0 flex-1">
              <code className="break-all font-mono text-xs text-zinc-200">
                {token}
              </code>
            </dd>
            <CopyButton
              value={token}
              label="Copy demo token"
              toastMessage="Demo token copied."
              variant="ghost"
              size="xs"
            />
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <dt className="w-20 shrink-0 text-xs text-zinc-500">Runtime</dt>
            <dd className="min-w-0 flex-1">
              <code className="break-all font-mono text-xs text-zinc-200">
                {endpointUrl}
              </code>
            </dd>
            <CopyButton
              value={endpointUrl}
              label="Copy demo runtime URL"
              toastMessage="Demo runtime URL copied."
              variant="ghost"
              size="xs"
            />
          </div>
        </dl>
        <div className="mt-4 flex flex-wrap items-center gap-3">
          <Button asChild size="sm">
            <Link href={`/p/${slug}`}>Open the demo project</Link>
          </Button>
          <Button
            type="button"
            size="sm"
            variant="outline"
            onClick={() => {
              void reset();
            }}
            disabled={resetting}
          >
            {resetting ? (
              <LoaderCircleIcon aria-hidden="true" className="animate-spin" />
            ) : (
              <RotateCcwIcon aria-hidden="true" />
            )}
            {resetting ? "Resetting…" : "Reset demo data"}
          </Button>
        </div>
        {message ? (
          <p
            role="status"
            className="mt-3 rounded-lg border border-lime-300/25 bg-lime-300/[0.05] px-3 py-2 text-xs text-lime-200"
          >
            {message}
          </p>
        ) : null}
      </section>

      <section className="rounded-xl border border-white/10 bg-white/[0.02] p-5">
        <h2 className="text-sm font-semibold text-zinc-100">Before a demo</h2>
        <ul className="mt-3 space-y-2 text-sm leading-6 text-zinc-400">
          <li>Reset the demo data so the log table starts empty and readable.</li>
          <li>
            Open the demo project in a second tab and keep the token handy; the
            demo token above is regenerated by the reset.
          </li>
          <li>
            Never demo with a project that expires during the session. Create a
            fresh project if the demo project is close to its expiry date.
          </li>
        </ul>
      </section>
    </div>
  );
}
